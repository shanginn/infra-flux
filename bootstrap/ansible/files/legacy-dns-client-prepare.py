#!/usr/bin/env python3
"""Install only the pinned legacy DNS VPN client, with a persistent start gate.

JSON stdin; inspect is read-only. No enrollment, firewall edits, route changes,
dependency installation, service activation, or automatic recovery is supported.
"""
import fcntl
import hashlib
import ipaddress
import json
import os
from pathlib import Path
import re
import stat
import subprocess
import sys
import tempfile
import urllib.request

OWNER = 'infra-flux/legacy-dns-client-prepare'
VERSION = '1.104.1'
URL = 'https://pkgs.tailscale.com/stable/tailscale_1.104.1_amd64.deb'
PACKAGE_SHA256 = '509753a4ff223efc70234e7f539afc51f743b3af043d9e55313960bd7327700f'
PACKAGE_SIZE = 40512672
ROOT = Path('/etc/infra-flux')
STATE = ROOT / 'legacy-dns-client-preparation.json'
APPROVAL = ROOT / 'legacy-dns-client-start-approved'
DROP_DIR = Path('/etc/systemd/system/tailscaled.service.d')
DROP = DROP_DIR / '00-infra-preparation-gate.conf'
DROP_CONTENT = ('# Managed by infra-flux/legacy-dns-client-prepare.\n'
                '# Enrollment must explicitly remove this gate after separate review.\n'
                '[Unit]\nConditionPathExists=' + str(APPROVAL) + '\n')
SERVICES = ('k3s.service', 'docker.service', 'containerd.service',
            'wg-quick@wg-homelab.service', 'ssh.service', 'sshd.service')
SERVICE_FIELDS = ('LoadState', 'ActiveState', 'SubState', 'MainPID',
                  'ExecMainStartTimestampMonotonic', 'ActiveEnterTimestampMonotonic',
                  'FragmentPath', 'UnitFileState')
ABSENT_PATHS = ('/var/lib/tailscale', '/run/tailscale', '/var/cache/tailscale',
                '/usr/local/bin/tailscale', '/usr/local/bin/tailscaled',
                '/etc/tailscale', '/etc/tailscaled.conf')
INSTALLED_HASHES = {
    '/usr/bin/tailscale': '64aed443d6454865bdcabb40030b052c4b89cf9a4436c499d41afc502c0ec28d',
    '/usr/sbin/tailscaled': '8b16e5cb5c480f58ae6325d036e7b7a2362e8df07fb9cfbf31d16e2b6c7df76c',
    '/lib/systemd/system/tailscaled.service': 'b975caad21103ab3086998b56e0003181e7473819921226bb22d243a4df7e7f6',
    '/etc/default/tailscaled': 'dccbbcb1f19cf455e41c9f2551733ab92433d162bd7d17564390db21f76bff93',
}


def require(value, message):
    if not value:
        raise RuntimeError(message)


def sha(value):
    return hashlib.sha256(value).hexdigest()


def digest(value):
    return sha(json.dumps(value, sort_keys=True, separators=(',', ':')).encode())


def command(argv, allowed=(0,), timeout=30):
    p = subprocess.run(argv, capture_output=True, text=True, timeout=timeout,
                       env={**os.environ, 'LC_ALL': 'C', 'DEBIAN_FRONTEND': 'noninteractive'})
    require(p.returncode in allowed, 'Command failed: ' + Path(argv[0]).name)
    return p.returncode, p.stdout


def output(argv, **kwargs):
    return command(argv, **kwargs)[1]


def json_command(argv, allowed=(0,)):
    rc, text = command(argv, allowed=allowed)
    return {'rc': rc, 'value': json.loads(text) if rc == 0 else None}


def secure_regular(path, private=False):
    s = path.lstat()
    require(stat.S_ISREG(s.st_mode) and s.st_uid == 0 and
            not s.st_mode & (0o077 if private else 0o022), 'Unsafe owned file: ' + str(path))
    return s


def secure_directory(path):
    s = path.lstat()
    require(stat.S_ISDIR(s.st_mode) and s.st_uid == 0 and not s.st_mode & 0o022,
            'Unsafe directory: ' + str(path))


def sync_directory(path):
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def file_identity(path):
    p = Path(path)
    s = p.lstat()
    return {'sha256': sha(p.read_bytes()), 'mode': stat.S_IMODE(s.st_mode),
            'uid': s.st_uid, 'gid': s.st_gid,
            'link': os.readlink(p) if stat.S_ISLNK(s.st_mode) else None}


def service(name):
    text = output(['systemctl', 'show', name, '--no-pager'] +
                  ['--property=' + k for k in SERVICE_FIELDS])
    result = dict(line.split('=', 1) for line in text.splitlines() if '=' in line)
    require(set(result) == set(SERVICE_FIELDS), 'Incomplete service identity')
    return result


def firewall_normalized(text):
    # Counters and generated timestamps change without a configuration change.
    text = re.sub(r'\[\d+:\d+\]', '[COUNTERS]', text)
    return '\n'.join(line for line in text.splitlines()
                     if not line.startswith(('# Generated by ', '# Completed on ')))


def network_stable(value):
    if isinstance(value, dict):
        return {k: network_stable(v) for k, v in value.items()
                if k not in ('valid_life_time', 'preferred_life_time', 'expires')}
    if isinstance(value, list):
        return sorted((network_stable(v) for v in value), key=lambda v: json.dumps(v, sort_keys=True))
    return value


def package_inventory():
    text = output(['dpkg-query', '-W', '-f=${binary:Package}\t${db:Status-Abbrev}\t${Version}\n'])
    return sorted(line for line in text.splitlines() if line.split('\t')[0] != 'tailscale')


def baseline(admin_address):
    admin_address = str(ipaddress.ip_address(admin_address))
    os_release = dict(line.split('=', 1) for line in Path('/etc/os-release').read_text().splitlines()
                      if '=' in line)
    os_release = {k: v.strip('"') for k, v in os_release.items()}
    require(os_release.get('ID') == 'debian' and os_release.get('VERSION_ID') in ('11', '13'),
            'Only reviewed Debian 11/13 hosts are supported')
    require(output(['dpkg', '--print-architecture']).strip() == 'amd64', 'Require amd64')
    require(Path('/dev/net/tun').is_char_device(), 'Existing TUN device required')
    net = {}
    for family in ('-4', '-6'):
        # IPv6 may be completely disabled. Preserve its exact observed status.
        for kind, args in (('routes', ['route', 'show', 'table', 'all']), ('rules', ['rule', 'show'])):
            net[family + kind] = json_command(['ip', '-j', family] + args, allowed=(0, 2, 255))
    net['addresses'] = json_command(['ip', '-j', 'address', 'show'])
    net['admin_route'] = json_command(['ip', '-j', 'route', 'get', admin_address])
    net['admin_address'] = admin_address
    fw = {}
    for tool in ('iptables-save', 'ip6tables-save'):
        fw[tool] = sha(firewall_normalized(output([tool])).encode())
    return {'format': 1, 'machine_id_sha256': sha(Path('/etc/machine-id').read_bytes()),
            'boot_id': Path('/proc/sys/kernel/random/boot_id').read_text().strip(),
            'os': {k: os_release[k] for k in ('ID', 'VERSION_ID')}, 'arch': 'amd64',
            'services': {name: service(name) for name in SERVICES}, 'network': network_stable(net),
            'hosts': file_identity('/etc/hosts'), 'resolver': file_identity('/etc/resolv.conf'),
            'firewall': fw, 'other_packages_sha256': digest(package_inventory())}


def assert_baseline(observed, expected):
    require(isinstance(expected, dict) and observed == expected,
            'Reviewed host/service/route/DNS/firewall/package baseline changed')


def no_client_process():
    for path in Path('/proc').glob('[0-9]*/comm'):
        try:
            name = path.read_text().strip()
        except (FileNotFoundError, ProcessLookupError):
            continue
        require(name not in ('tailscaled', 'tailscale'), 'Existing client process; preparation refused')


def inactive_never_started():
    s = service('tailscaled.service')
    require(s['ActiveState'] == 'inactive' and s['SubState'] == 'dead' and
            s['MainPID'] == '0' and s['ExecMainStartTimestampMonotonic'] == '0',
            'Client was activated or has an unexpected state')
    no_client_process()
    return s


def paths_absent(paths):
    for value in paths:
        require(not os.path.lexists(value), 'Unexpected client path: ' + str(value))


def tailscale_package():
    rc, text = command(['dpkg-query', '-W', '-f=${db:Status-Abbrev}\t${Version}', 'tailscale'], allowed=(0, 1))
    return text.strip() if rc == 0 else None


def check_unit_overrides(prepared=False):
    # A type-wide or later runtime drop-in can reset ConditionPathExists. Check
    # every search directory, including generator/transient/control paths.
    paths = output(['systemd-analyze', 'unit-paths']).splitlines()
    require(paths and all(p.startswith('/') for p in paths), 'Unexpected systemd unit search paths')
    seen = set()
    for root in map(Path, paths):
        for name in ('service.d', 'tailscaled.service.d'):
            candidate = root / name
            if not os.path.lexists(candidate):
                continue
            resolved = candidate.resolve()
            if resolved in seen:
                continue
            seen.add(resolved)
            if prepared and candidate == DROP_DIR:
                secure_directory(candidate)
                require(sorted(p.name for p in candidate.iterdir()) == [DROP.name],
                        'Unexpected owned-unit drop-in')
            else:
                raise RuntimeError('Preexisting systemd drop-in can override start gate: ' + str(candidate))
        unit = root / 'tailscaled.service'
        if os.path.lexists(unit):
            require(prepared and unit.resolve() == Path('/lib/systemd/system/tailscaled.service').resolve(),
                    'Unexpected unit override: ' + str(unit))


def assert_fresh():
    require(tailscale_package() is None, 'Existing unmanaged package; no adoption or upgrade')
    s = inactive_never_started()
    require(s['LoadState'] == 'not-found', 'Existing client service is not owned')
    paths_absent(list(ABSENT_PATHS) + list(INSTALLED_HASHES) + [DROP_DIR, APPROVAL,
        '/etc/systemd/system/tailscaled.service', '/run/systemd/system/tailscaled.service'])
    check_unit_overrides()
    require(not output(['dpkg', '--audit']).strip(), 'dpkg has unfinished work')
    for name in ('iptables', 'iproute2'):
        require(output(['dpkg-query', '-W', '-f=${db:Status-Abbrev}', name]) == 'ii ',
                'Dependency must already be installed: ' + name)


def validate_package(path):
    secure_regular(path, private=True)
    require(path.stat().st_size == PACKAGE_SIZE and sha(path.read_bytes()) == PACKAGE_SHA256,
            'Official package size/digest mismatch')
    values = output(['dpkg-deb', '-f', str(path), 'Package', 'Version', 'Architecture', 'Depends'])
    require(values == 'Package: tailscale\nVersion: 1.104.1\nArchitecture: amd64\nDepends: iptables\n',
            'Unexpected package metadata')


def read_state():
    secure_regular(STATE, private=True)
    state = json.loads(STATE.read_text())
    require(state.get('managed_by') == OWNER and state.get('format') == 1 and
            state.get('package_sha256') == PACKAGE_SHA256, 'Wrong preparation record identity')
    return state


def save(state):
    require(not STATE.is_symlink(), 'Refuse symlink record')
    fd, name = tempfile.mkstemp(prefix='.legacy-dns-preparation-', dir=ROOT)
    try:
        with os.fdopen(fd, 'w') as f:
            json.dump(state, f, sort_keys=True, indent=2)
            f.write('\n'); f.flush(); os.fsync(f.fileno())
        os.replace(name, STATE)
        fd = os.open(ROOT, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def verify_prepared():
    require(tailscale_package() == 'ii \t' + VERSION, 'Prepared package identity changed')
    paths_absent(ABSENT_PATHS + (APPROVAL,))
    secure_directory(DROP_DIR)
    require(sorted(p.name for p in DROP_DIR.iterdir()) == [DROP.name], 'Unexpected service drop-ins')
    secure_regular(DROP)
    require(DROP.read_text() == DROP_CONTENT, 'Start gate changed')
    check_unit_overrides(prepared=True)
    for name, expected in INSTALLED_HASHES.items():
        secure_regular(Path(name))
        require(sha(Path(name).read_bytes()) == expected, 'Installed file differs: ' + name)
    require(not output(['dpkg', '--verify', 'tailscale']).strip(), 'Installed package differs')
    s = inactive_never_started()
    require(s['LoadState'] == 'loaded' and s['UnitFileState'] == 'disabled',
            'Prepared client must remain disabled')
    require(output(['systemctl', 'show', 'tailscaled.service', '--property=DropInPaths', '--value']).strip()
            == str(DROP), 'Effective start-gate drop-ins differ')
    require(not output(['dpkg', '--audit']).strip(), 'dpkg has unfinished work')


def prepare(settings):
    require(settings.get('enabled') is True, 'Explicit preparation enable required')
    current = baseline(settings['admin_address'])
    assert_baseline(current, settings.get('expected'))
    if ROOT.exists():
        secure_directory(ROOT)
    if os.path.lexists(STATE):
        state = read_state()
        require(state.get('phase') == 'verified', 'Interrupted preparation: inspect manually, never blindly retry')
        assert_baseline(current, state['baseline'])
        verify_prepared()
        return {'changed': False, 'prepared': True, 'client_started': False}
    assert_fresh()
    # No package resolver is invoked: the only installed package is this exact deb.
    with tempfile.TemporaryDirectory(prefix='infra-legacy-dns-') as directory:
        package = Path(directory) / 'tailscale.deb'
        with urllib.request.urlopen(URL, timeout=60) as response:
            require(response.geturl() == URL, 'Unexpected package redirect')
            data = response.read(PACKAGE_SIZE + 1)
        package.write_bytes(data); package.chmod(0o600)
        validate_package(package)
        # Recheck immediately before installing any owned files.
        assert_baseline(baseline(settings['admin_address']), current)
        assert_fresh()
        ROOT.mkdir(mode=0o700, exist_ok=True)
        secure_directory(ROOT)
        sync_directory(ROOT.parent)
        state = {'managed_by': OWNER, 'format': 1, 'phase': 'install-intent',
                 'package_sha256': PACKAGE_SHA256, 'baseline': current}
        save(state)
        # postinst explicitly calls deb-systemd-invoke restart; this persistent
        # condition is installed first and prevents ExecStart and ExecStopPost.
        DROP_DIR.mkdir(mode=0o755)
        fd = os.open(DROP, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644)
        with os.fdopen(fd, 'w') as f:
            f.write(DROP_CONTENT); f.flush(); os.fsync(f.fileno())
        sync_directory(DROP_DIR)
        sync_directory(DROP_DIR.parent)
        output(['systemctl', 'daemon-reload'])
        check_unit_overrides(prepared=True)
        paths_absent([APPROVAL])
        output(['dpkg', '--install', str(package)], timeout=180)
        output(['systemctl', 'disable', 'tailscaled.service'])
        verify_prepared()
        assert_baseline(baseline(settings['admin_address']), current)
        state['phase'] = 'verified'
        save(state)
    return {'changed': True, 'prepared': True, 'client_started': False}


def main():
    os.umask(0o077)
    require(os.geteuid() == 0, 'Root required for complete read-only guards')
    settings = json.load(sys.stdin)
    require(settings.get('action', 'inspect') in ('inspect', 'prepare'), 'Unsupported action')
    if settings.get('action', 'inspect') == 'inspect':
        result = {'baseline': baseline(settings['admin_address']),
                  'installation': {'package': tailscale_package(), 'service': service('tailscaled.service'),
                                   'owned_record': os.path.lexists(STATE)}}
    else:
        # One installer per host. A pending durable record blocks every retry.
        name = '/run/lock/infra-legacy-dns-client-prepare.lock'
        fd = os.open(name, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
        s = os.fstat(fd)
        require(stat.S_ISREG(s.st_mode) and s.st_uid == 0 and not s.st_mode & 0o077,
                'Unsafe preparation lock')
        with os.fdopen(fd, 'a') as lock:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            result = prepare(settings)
    print(json.dumps(result, sort_keys=True))


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        # Raw command outputs and private input are never emitted on failure.
        print(json.dumps({'ok': False, 'error': str(error) if isinstance(error, RuntimeError)
                          else type(error).__name__, 'retry': 'Inspect durable record; do not blindly retry'}))
        sys.exit(1)

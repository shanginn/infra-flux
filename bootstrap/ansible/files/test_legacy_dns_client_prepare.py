#!/usr/bin/env python3
"""Offline tests: never run a package manager or service operation."""
import importlib.util
import pathlib
import tempfile
import unittest
from unittest.mock import patch
import io
import json

SPEC = importlib.util.spec_from_file_location('legacy_prepare',
    pathlib.Path(__file__).with_name('legacy-dns-client-prepare.py'))
M = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(M)


class Guards(unittest.TestCase):
    def test_baseline_rejects_admin_route_change(self):
        with self.assertRaisesRegex(RuntimeError, 'baseline changed'):
            M.assert_baseline({'network': {'gateway': 'changed'}}, {'network': {'gateway': 'before'}})

    def test_baseline_rejects_restarted_old_service(self):
        with self.assertRaises(RuntimeError):
            M.assert_baseline({'pid': 2, 'start': 10}, {'pid': 2, 'start': 9})

    def test_baseline_requires_explicit_input(self):
        with self.assertRaises(RuntimeError):
            M.assert_baseline({}, None)

    def test_counters_and_generation_time_are_not_config(self):
        a = '# Generated by iptables-save at one\n:FORWARD DROP [1:9]\n-A X -j ACCEPT\n# Completed on one\n'
        b = '# Generated by iptables-save at two\n:FORWARD DROP [4:88]\n-A X -j ACCEPT\n# Completed on two\n'
        self.assertEqual(M.firewall_normalized(a), M.firewall_normalized(b))
        self.assertNotEqual(M.firewall_normalized(a), M.firewall_normalized(a.replace('DROP', 'ACCEPT')))

    def test_network_lifetimes_ignored_routes_retained(self):
        a = [{'dst': 'default', 'gateway': 'a', 'valid_life_time': 10}, {'dst': 'private'}]
        b = [{'dst': 'private'}, {'dst': 'default', 'gateway': 'a', 'valid_life_time': 9}]
        self.assertEqual(M.network_stable(a), M.network_stable(b))
        b[1]['gateway'] = 'b'
        self.assertNotEqual(M.network_stable(a), M.network_stable(b))

    def test_fresh_refuses_existing_unmanaged_package(self):
        with patch.object(M, 'tailscale_package', return_value='ii \t1.104.1'):
            with self.assertRaisesRegex(RuntimeError, 'unmanaged'):
                M.assert_fresh()

    def test_fresh_refuses_preexisting_unit(self):
        with patch.object(M, 'tailscale_package', return_value=None), \
             patch.object(M, 'inactive_never_started', return_value={'LoadState': 'loaded'}):
            with self.assertRaisesRegex(RuntimeError, 'not owned'):
                M.assert_fresh()

    def test_started_then_stopped_daemon_is_not_fresh(self):
        s = {'ActiveState': 'inactive', 'SubState': 'dead', 'MainPID': '0',
             'ExecMainStartTimestampMonotonic': '123'}
        with patch.object(M, 'service', return_value=s):
            with self.assertRaisesRegex(RuntimeError, 'activated'):
                M.inactive_never_started()

    def test_broken_symlink_is_not_absent(self):
        with tempfile.TemporaryDirectory() as directory:
            p = pathlib.Path(directory) / 'state'; p.symlink_to('/not-a-real-target')
            with self.assertRaises(RuntimeError):
                M.paths_absent([p])

    def test_preparation_requires_explicit_enable(self):
        with patch.object(M, 'baseline') as baseline:
            with self.assertRaises(RuntimeError):
                M.prepare({'enabled': False})
            baseline.assert_not_called()

    def test_pending_install_never_retries_package_dispatch(self):
        with patch.object(M, 'baseline', return_value={'identity': 1}), \
             patch.object(M, 'secure_directory'), \
             patch.object(M.os.path, 'lexists', return_value=True), \
             patch.object(M, 'read_state', return_value={'phase': 'install-intent'}), \
             patch.object(M, 'assert_fresh') as fresh, \
             patch.object(M.urllib.request, 'urlopen') as download:
            with self.assertRaisesRegex(RuntimeError, 'Interrupted'):
                M.prepare({'enabled': True, 'admin_address': '192.0.2.1', 'expected': {'identity': 1}})
            fresh.assert_not_called(); download.assert_not_called()

    def test_exact_verified_preparation_is_noop(self):
        with patch.object(M, 'baseline', return_value={'identity': 1}), \
             patch.object(M, 'secure_directory'), \
             patch.object(M.os.path, 'lexists', return_value=True), \
             patch.object(M, 'read_state', return_value={'phase': 'verified', 'baseline': {'identity': 1}}), \
             patch.object(M, 'verify_prepared') as verify, \
             patch.object(M.urllib.request, 'urlopen') as download:
            r = M.prepare({'enabled': True, 'admin_address': '192.0.2.1', 'expected': {'identity': 1}})
            self.assertFalse(r['changed']); self.assertFalse(r['client_started'])
            verify.assert_called_once(); download.assert_not_called()

    def test_verified_record_from_other_host_is_rejected(self):
        with patch.object(M, 'baseline', return_value={'identity': 1}), \
             patch.object(M, 'secure_directory'), \
             patch.object(M.os.path, 'lexists', return_value=True), \
             patch.object(M, 'read_state', return_value={'phase': 'verified', 'baseline': {'identity': 2}}), \
             patch.object(M, 'verify_prepared') as verify:
            with self.assertRaises(RuntimeError):
                M.prepare({'enabled': True, 'admin_address': '192.0.2.1', 'expected': {'identity': 1}})
            verify.assert_not_called()

    def test_package_digest_failure_precedes_metadata_execution(self):
        with tempfile.TemporaryDirectory() as directory:
            p = pathlib.Path(directory) / 'package'; p.write_bytes(b'not a deb')
            with patch.object(M, 'secure_regular'), patch.object(M, 'output') as output:
                with self.assertRaisesRegex(RuntimeError, 'digest'):
                    M.validate_package(p)
                output.assert_not_called()

    def test_start_gate_is_persistent_and_requires_absent_approval(self):
        self.assertIn('ConditionPathExists=' + str(M.APPROVAL), M.DROP_CONTENT)
        self.assertNotIn('ConditionPathExists=!', M.DROP_CONTENT)

    def test_runtime_dropin_cannot_reset_condition(self):
        with tempfile.TemporaryDirectory() as directory:
            root = pathlib.Path(directory)
            override = root / 'tailscaled.service.d'; override.mkdir()
            (override / '99-reset.conf').write_text('[Unit]\nConditionPathExists=\n')
            with patch.object(M, 'output', return_value=str(root) + '\n'):
                with self.assertRaisesRegex(RuntimeError, 'override start gate'):
                    M.check_unit_overrides(prepared=True)

    def test_type_wide_dropin_is_not_silently_accepted(self):
        with tempfile.TemporaryDirectory() as directory:
            root = pathlib.Path(directory); (root / 'service.d').mkdir()
            with patch.object(M, 'output', return_value=str(root) + '\n'):
                with self.assertRaises(RuntimeError):
                    M.check_unit_overrides()

    def test_install_intent_and_gate_precede_only_package_dispatch(self):
        with tempfile.TemporaryDirectory() as directory:
            root = pathlib.Path(directory)
            state = root / 'preparation.json'; dropdir = root / 'tailscaled.service.d'
            drop = dropdir / '00-infra-preparation-gate.conf'; approval = root / 'approve'
            response = io.BytesIO(b'package'); response.geturl = lambda: M.URL
            events = []
            synced = []
            def run(argv, **kwargs):
                events.append(argv)
                if argv[:2] == ['dpkg', '--install']:
                    self.assertEqual(json.loads(state.read_text())['phase'], 'install-intent')
                    self.assertEqual(drop.read_text(), M.DROP_CONTENT)
                    self.assertFalse(approval.exists())
                    self.assertEqual(events[-2], ['systemctl', 'daemon-reload'])
                    self.assertIn(dropdir, synced)
                    self.assertIn(dropdir.parent, synced)
                return ''
            def verify():
                self.assertEqual(json.loads(state.read_text())['phase'], 'install-intent')
                self.assertEqual(events[-1], ['systemctl', 'disable', 'tailscaled.service'])
            with patch.multiple(M, ROOT=root, STATE=state, DROP_DIR=dropdir, DROP=drop, APPROVAL=approval), \
                 patch.object(M, 'baseline', return_value={'identity': 1}), \
                 patch.object(M, 'secure_directory'), patch.object(M, 'assert_fresh'), \
                 patch.object(M, 'check_unit_overrides'), patch.object(M, 'validate_package'), \
                 patch.object(M, 'sync_directory', side_effect=synced.append), \
                 patch.object(M.urllib.request, 'urlopen', return_value=response), \
                 patch.object(M, 'output', side_effect=run), \
                 patch.object(M, 'verify_prepared', side_effect=verify):
                result = M.prepare({'enabled': True, 'admin_address': '192.0.2.1', 'expected': {'identity': 1}})
            self.assertTrue(result['prepared'])
            self.assertEqual(json.loads(state.read_text())['phase'], 'verified')
            self.assertEqual(sum(a[:2] == ['dpkg', '--install'] for a in events), 1)
            self.assertFalse(any('start' in a or 'restart' in a or 'enable' in a for a in events))


if __name__ == '__main__':
    unittest.main()
